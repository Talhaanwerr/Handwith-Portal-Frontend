/** Round heads (party guests wear hats on them) use the face, not the body. */
export const FLUENT_HEAD: Readonly<Record<string, string>> = {
  cat: "cat_face",
  dog: "dog_face",
  monkey: "monkey_face",
  tiger: "tiger_face",
};

/** The URL of the 3D picture for a word id, or null when it has none. */
export function fluentSrc(id: string, head = false): string | null {
  const file = (head && FLUENT_HEAD[id]) || FLUENT_PICTURE[id];
  return file ? `${FLUENT_BASE}/${file}.png` : null;
}
